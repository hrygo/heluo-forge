import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';

const root = new URL('./', import.meta.url);
const modelSource = await readFile(new URL('model.mjs', root), 'utf8');
const viewSource = await readFile(new URL('view.js', root), 'utf8');
const inlineModel = modelSource.replace(/^export\s+(?=function\s)/gm, '');
if (/^\s*(?:import|export)\s/m.test(inlineModel + '\n' + viewSource)) throw new Error('Client sources must be import-free pure functions');
const output = `// Generated by build.mjs from model.mjs and view.js. Do not edit directly.
window.__ModuleLoader__.load({
  id: '@local/heluo-enterprise-settings-demo',
  factory(require) {
    const React = require('react');
${inlineModel}
    const model = Object.freeze({ initialState, reduce, readiness, validatePublic });
${viewSource}
    function apply(ctx) {
      const NS = 'heluo-settings-demo';
      const t = ctx.locale.bind(NS);
      ctx.effect(() => ctx.locale.register(NS, { zh: demoCopy.zh, en: demoCopy.en }), 'heluo-settings-demo: locale');
      const DemoPage = createDemoView(React, model, t);
      ctx.effect(() => ctx.slots.inject('settings.section', () =>
        ctx.slots.register({
          name: 'settings.section',
          id: 'heluo-settings-demo',
          order: 25,
          label: () => t('sectionLabel'),
          locale: NS,
          inject: () => ({ t }),
        }, DemoPage)
      ), 'heluo-settings-demo: settings section');
    }
    const inject = ['slots', 'locale'];
    return { apply, inject };
  },
});
`;
new Script(output, { filename: 'client.js' });
const target = new URL('client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('client.js is stale; run node demos/enterprise-settings/build.mjs');
  console.log('Client is current and syntactically valid.');
} else {
  await writeFile(target, output);
  console.log('Built ' + fileURLToPath(target));
}
